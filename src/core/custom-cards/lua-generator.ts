import type { Card } from '../../types/card.js';

export interface EffectSpec {
  type: string; // 'ignition' | 'trigger' | 'quick' | 'activate' | 'sp_summon' | 'continuous' | string;
  category?: string; // 'CATEGORY_DESTROY' | 'CATEGORY_SPECIAL_SUMMON' | 'CATEGORY_TOHAND' | 'CATEGORY_SEARCH' | etc.
  isHOPT?: boolean;
  targets?: boolean;
  description?: string;
  code?: string; // e.g. 'EVENT_FREE_CHAIN', 'EVENT_SUMMON_SUCCESS', 'EVENT_CHAINING'
  range?: string; // e.g. 'LOCATION_MZONE', 'LOCATION_HAND', 'LOCATION_GRAVE'
}

/**
 * Normalizes category constant string ensuring proper prefix.
 */
function normalizeCategory(cat?: string): string {
  if (!cat) return 'CATEGORY_DESTROY';
  const trimmed = cat.trim();
  if (trimmed.startsWith('CATEGORY_')) return trimmed;
  const uppercase = trimmed.toUpperCase().replace(/\s+/g, '_');
  return `CATEGORY_${uppercase}`;
}

/**
 * Generates clean, robust, syntax-accurate EDOPro / ProjectIgnis ocgcore Lua scripts.
 */
export function generateLuaScript(
  card: Partial<Card>,
  id: number,
  effectsSpec?: EffectSpec[]
): string {
  const cardName = card.name || 'Custom Card';
  const frameType = (card.frameType || '').toLowerCase();
  const cardType = (card.type || '').toLowerCase();
  const archetype = card.archetype || '';
  const race = (card.race || 'WARRIOR').toUpperCase().replace(/[\s-]/g, '_');
  const level = card.level || 4;
  const linkVal = card.linkval || 2;

  const isSpell = cardType.includes('spell') || frameType === 'spell';
  const isTrap = cardType.includes('trap') || frameType === 'trap';
  const isMonster = !isSpell && !isTrap;
  const isNormal = cardType.includes('normal') && isMonster;
  const isSynchro = frameType === 'synchro' || cardType.includes('synchro');
  const isXyz = frameType === 'xyz' || cardType.includes('xyz');
  const isFusion = frameType === 'fusion' || cardType.includes('fusion');
  const isLink = frameType === 'link' || cardType.includes('link');
  const isRitual = frameType === 'ritual' || cardType.includes('ritual');

  const lines: string[] = [];

  // Header
  lines.push(`-- Custom Card: ${cardName} (ID: ${id})`);
  lines.push(`-- Generated by Yu-Gi-Oh! Assistant`);
  lines.push(`local s, id = GetID()`);
  lines.push(`function s.initial_effect(c)`);

  // Extra Deck / Ritual summoning procedures
  if (isSynchro) {
    lines.push(`\tc:EnableReviveLimit()`);
    lines.push(`\tSynchro.AddProcedure(c, nil, 1, 1, Synchro.NonTuner(nil), 1, 99)`);
  } else if (isXyz) {
    lines.push(`\tc:EnableReviveLimit()`);
    lines.push(`\tXyz.AddProcedure(c, nil, ${level}, 2)`);
  } else if (isFusion) {
    lines.push(`\tc:EnableReviveLimit()`);
    lines.push(`\tFusion.AddProcMixN(c, true, true, aux.FilterBoolFunctionEx(Card.IsRace, RACE_${race}), 2)`);
  } else if (isLink) {
    lines.push(`\tc:EnableReviveLimit()`);
    lines.push(`\tLink.AddProcedure(c, nil, 2, ${linkVal})`);
  } else if (isRitual) {
    lines.push(`\tc:EnableReviveLimit()`);
  }

  // Determine effect specifications
  let specs: EffectSpec[] = [];
  if (effectsSpec && effectsSpec.length > 0) {
    specs = effectsSpec;
  } else if (isNormal) {
    // Normal monster has no effects
    specs = [];
  } else if (isSpell) {
    if (cardType.includes('quick-play')) {
      specs.push({
        type: 'activate',
        category: 'CATEGORY_DESTROY',
        isHOPT: true,
        targets: true,
        description: 'Quick-Play Spell activation to target and destroy 1 card on the field',
      });
    } else if (cardType.includes('continuous') || cardType.includes('field')) {
      specs.push({
        type: 'activate',
        category: 'CATEGORY_TOHAND',
        isHOPT: true,
        targets: false,
        description: 'Continuous activation: search archetype card on activation',
      });
      specs.push({
        type: 'ignition',
        category: 'CATEGORY_SPECIAL_SUMMON',
        isHOPT: true,
        targets: false,
        range: 'LOCATION_SZONE',
        description: 'Once per turn effect while face-up on field',
      });
    } else {
      // Normal Spell
      specs.push({
        type: 'activate',
        category: 'CATEGORY_SEARCH',
        isHOPT: true,
        targets: false,
        description: 'Normal Spell activation to add 1 archetype card to hand',
      });
    }
  } else if (isTrap) {
    if (cardType.includes('counter')) {
      specs.push({
        type: 'activate',
        code: 'EVENT_CHAINING',
        category: 'CATEGORY_NEGATE',
        isHOPT: true,
        targets: false,
        description: 'Counter Trap to negate card activation and destroy it',
      });
    } else {
      specs.push({
        type: 'activate',
        category: 'CATEGORY_DESTROY',
        isHOPT: true,
        targets: true,
        description: 'Trap activation to target and destroy 1 card your opponent controls',
      });
    }
  } else {
    // Effect Monster default effects
    specs.push({
      type: 'ignition',
      category: 'CATEGORY_SPECIAL_SUMMON',
      isHOPT: true,
      targets: false,
      range: 'LOCATION_HAND',
      description: 'Special Summon this card from hand by its own effect',
    });
    specs.push({
      type: 'trigger',
      category: 'CATEGORY_SEARCH',
      isHOPT: true,
      targets: false,
      code: 'EVENT_SUMMON_SUCCESS',
      description: 'Trigger on summon to search 1 archetype card',
    });
  }

  // Generate effect registration in s.initial_effect
  specs.forEach((spec, idx) => {
    const effNum = idx + 1;
    const effType = spec.type.toLowerCase();
    const cat = normalizeCategory(spec.category);

    lines.push(`\t-- Effect ${effNum}: ${spec.description || spec.type}`);
    lines.push(`\tlocal e${effNum} = Effect.CreateEffect(c)`);

    if (spec.description) {
      lines.push(`\te${effNum}:SetDescription(aux.Stringid(id, ${idx}))`);
    }

    if (cat) {
      lines.push(`\te${effNum}:SetCategory(${cat})`);
    }

    // Effect Type & Code
    if (effType === 'activate') {
      lines.push(`\te${effNum}:SetType(EFFECT_TYPE_ACTIVATE)`);
      if (spec.code) {
        lines.push(`\te${effNum}:SetCode(${spec.code})`);
      } else {
        lines.push(`\te${effNum}:SetCode(EVENT_FREE_CHAIN)`);
      }
    } else if (effType === 'trigger') {
      lines.push(`\te${effNum}:SetType(EFFECT_TYPE_SINGLE + EFFECT_TYPE_TRIGGER_O)`);
      lines.push(`\te${effNum}:SetProperty(EFFECT_FLAG_DELAY)`);
      lines.push(`\te${effNum}:SetCode(${spec.code || 'EVENT_SUMMON_SUCCESS'})`);
    } else if (effType === 'quick') {
      lines.push(`\te${effNum}:SetType(EFFECT_TYPE_QUICK_O)`);
      lines.push(`\te${effNum}:SetCode(${spec.code || 'EVENT_FREE_CHAIN'})`);
      lines.push(`\te${effNum}:SetRange(${spec.range || 'LOCATION_MZONE'})`);
    } else if (effType === 'sp_summon' || (effType === 'ignition' && spec.range === 'LOCATION_HAND')) {
      lines.push(`\te${effNum}:SetType(EFFECT_TYPE_IGNITION)`);
      lines.push(`\te${effNum}:SetRange(LOCATION_HAND)`);
    } else if (effType === 'continuous') {
      lines.push(`\te${effNum}:SetType(EFFECT_TYPE_FIELD + EFFECT_TYPE_CONTINUOUS)`);
      lines.push(`\te${effNum}:SetCode(${spec.code || 'EVENT_ADJUST'})`);
      lines.push(`\te${effNum}:SetRange(${spec.range || 'LOCATION_MZONE'})`);
    } else {
      // standard ignition
      lines.push(`\te${effNum}:SetType(EFFECT_TYPE_IGNITION)`);
      lines.push(`\te${effNum}:SetRange(${spec.range || 'LOCATION_MZONE'})`);
    }

    // Target property
    if (spec.targets) {
      lines.push(`\te${effNum}:SetProperty(EFFECT_FLAG_CARD_TARGET)`);
    }

    // HOPT / SOPT count limit
    if (spec.isHOPT) {
      lines.push(`\te${effNum}:SetCountLimit(1, id)`);
    } else {
      lines.push(`\te${effNum}:SetCountLimit(1)`);
    }

    // Cost, Target, Operation
    lines.push(`\te${effNum}:SetCost(s.cost${effNum})`);
    lines.push(`\te${effNum}:SetTarget(s.target${effNum})`);
    lines.push(`\te${effNum}:SetOperation(s.operation${effNum})`);
    lines.push(`\tc:RegisterEffect(e${effNum})`);

    // For trigger on Normal or Special summon
    if (effType === 'trigger' && (!spec.code || spec.code === 'EVENT_SUMMON_SUCCESS')) {
      lines.push(`\tlocal e${effNum}_b = e${effNum}:Clone()`);
      lines.push(`\te${effNum}_b:SetCode(EVENT_SPSUMMON_SUCCESS)`);
      lines.push(`\tc:RegisterEffect(e${effNum}_b)`);
    }
  });

  lines.push(`end`);
  lines.push(``);

  // Helper filter function for archetype if available
  if (archetype) {
    lines.push(`-- Filter for ${archetype} cards`);
    lines.push(`function s.filter(c)`);
    lines.push(`\treturn c:IsSetCard(SET_${archetype.toUpperCase().replace(/[\s-']/g, '_')}) and c:IsAbleToHand()`);
    lines.push(`end`);
    lines.push(``);
  }

  // Generate Functions for each effect
  specs.forEach((spec, idx) => {
    const effNum = idx + 1;
    const cat = normalizeCategory(spec.category);
    const effType = spec.type.toLowerCase();

    // Cost Function
    lines.push(`-- Cost for Effect ${effNum}`);
    lines.push(`function s.cost${effNum}(e, tp, eg, ep, ev, re, r, rp, chk)`);
    if (effType === 'sp_summon' || (effType === 'ignition' && spec.range === 'LOCATION_HAND')) {
      lines.push(`\tif chk == 0 then return true end`);
    } else if (spec.category === 'CATEGORY_NEGATE') {
      lines.push(`\tif chk == 0 then return e:GetHandler():IsAbleToGraveAsCost() end`);
      lines.push(`\tDuel.SendtoGrave(e:GetHandler(), REASON_COST)`);
    } else {
      lines.push(`\tif chk == 0 then return true end`);
    }
    lines.push(`end`);
    lines.push(``);

    // Target Function
    lines.push(`-- Target for Effect ${effNum}`);
    lines.push(`function s.target${effNum}(e, tp, eg, ep, ev, re, r, rp, chk, chkc)`);

    if (spec.targets) {
      lines.push(`\tif chkc then return chkc:IsLocation(LOCATION_ONFIELD) and chkc:IsControler(1 - tp) end`);
      lines.push(`\tif chk == 0 then return Duel.IsExistingTarget(nil, tp, 0, LOCATION_ONFIELD, 1, nil) end`);
      lines.push(`\tDuel.Hint(HINT_SELECTMSG, tp, HINTMSG_TARGET)`);
      lines.push(`\tlocal g = Duel.SelectTarget(tp, nil, tp, 0, LOCATION_ONFIELD, 1, 1, nil)`);
      lines.push(`\tDuel.SetOperationInfo(0, ${cat}, g, 1, 0, 0)`);
    } else if (cat === 'CATEGORY_SPECIAL_SUMMON') {
      if (effType === 'sp_summon' || spec.range === 'LOCATION_HAND') {
        lines.push(`\tif chk == 0 then return Duel.GetLocationCount(tp, LOCATION_MZONE) > 0`);
        lines.push(`\t\tand e:GetHandler():IsCanBeSpecialSummoned(e, 0, tp, false, false) end`);
        lines.push(`\tDuel.SetOperationInfo(0, CATEGORY_SPECIAL_SUMMON, e:GetHandler(), 1, 0, 0)`);
      } else {
        lines.push(`\tif chk == 0 then return Duel.GetLocationCount(tp, LOCATION_MZONE) > 0`);
        lines.push(`\t\tand Duel.IsExistingMatchingCard(Card.IsCanBeSpecialSummoned, tp, LOCATION_GRAVE + LOCATION_HAND, 0, 1, nil, e, 0, tp, false, false) end`);
        lines.push(`\tDuel.SetOperationInfo(0, CATEGORY_SPECIAL_SUMMON, nil, 1, tp, LOCATION_GRAVE + LOCATION_HAND)`);
      }
    } else if (cat === 'CATEGORY_SEARCH' || cat === 'CATEGORY_TOHAND') {
      lines.push(`\tif chk == 0 then return Duel.IsExistingMatchingCard(Card.IsAbleToHand, tp, LOCATION_DECK, 0, 1, nil) end`);
      lines.push(`\tDuel.SetOperationInfo(0, CATEGORY_TOHAND, nil, 1, tp, LOCATION_DECK)`);
    } else if (cat === 'CATEGORY_NEGATE') {
      lines.push(`\tif chk == 0 then return Duel.IsChainNegatable(ev) end`);
      lines.push(`\tDuel.SetOperationInfo(0, CATEGORY_NEGATE, eg, 1, 0, 0)`);
      lines.push(`\tif re:GetHandler():IsDestructable() and re:GetHandler():IsRelateToEffect(re) then`);
      lines.push(`\t\tDuel.SetOperationInfo(0, CATEGORY_DESTROY, eg, 1, 0, 0)`);
      lines.push(`\tend`);
    } else {
      lines.push(`\tif chk == 0 then return true end`);
    }

    lines.push(`end`);
    lines.push(``);

    // Operation Function
    lines.push(`-- Operation for Effect ${effNum}`);
    lines.push(`function s.operation${effNum}(e, tp, eg, ep, ev, re, r, rp)`);

    if (spec.targets) {
      lines.push(`\tlocal tc = Duel.GetFirstTarget()`);
      lines.push(`\tif tc and tc:IsRelateToEffect(e) then`);
      lines.push(`\t\tDuel.Destroy(tc, REASON_EFFECT)`);
      lines.push(`\tend`);
    } else if (cat === 'CATEGORY_SPECIAL_SUMMON') {
      if (effType === 'sp_summon' || spec.range === 'LOCATION_HAND') {
        lines.push(`\tlocal c = e:GetHandler()`);
        lines.push(`\tif c:IsRelateToEffect(e) and Duel.GetLocationCount(tp, LOCATION_MZONE) > 0 then`);
        lines.push(`\t\tDuel.SpecialSummon(c, 0, tp, tp, false, false, POS_FACEUP)`);
        lines.push(`\tend`);
      } else {
        lines.push(`\tif Duel.GetLocationCount(tp, LOCATION_MZONE) <= 0 then return end`);
        lines.push(`\tDuel.Hint(HINT_SELECTMSG, tp, HINTMSG_SPSUMMON)`);
        lines.push(`\tlocal g = Duel.SelectMatchingCard(tp, Card.IsCanBeSpecialSummoned, tp, LOCATION_GRAVE + LOCATION_HAND, 0, 1, 1, nil, e, 0, tp, false, false)`);
        lines.push(`\tif #g > 0 then`);
        lines.push(`\t\tDuel.SpecialSummon(g, 0, tp, tp, false, false, POS_FACEUP)`);
        lines.push(`\tend`);
      }
    } else if (cat === 'CATEGORY_SEARCH' || cat === 'CATEGORY_TOHAND') {
      lines.push(`\tDuel.Hint(HINT_SELECTMSG, tp, HINTMSG_ATOHAND)`);
      if (archetype) {
        lines.push(`\tlocal g = Duel.SelectMatchingCard(tp, s.filter, tp, LOCATION_DECK, 0, 1, 1, nil)`);
      } else {
        lines.push(`\tlocal g = Duel.SelectMatchingCard(tp, Card.IsAbleToHand, tp, LOCATION_DECK, 0, 1, 1, nil)`);
      }
      lines.push(`\tif #g > 0 then`);
      lines.push(`\t\tDuel.SendtoHand(g, nil, REASON_EFFECT)`);
      lines.push(`\t\tDuel.ConfirmCards(1 - tp, g)`);
      lines.push(`\tend`);
    } else if (cat === 'CATEGORY_NEGATE') {
      lines.push(`\tif Duel.NegateActivation(ev) and re:GetHandler():IsRelateToEffect(re) then`);
      lines.push(`\t\tDuel.Destroy(eg, REASON_EFFECT)`);
      lines.push(`\tend`);
    } else {
      lines.push(`\t-- Custom effect resolution logic`);
    }

    lines.push(`end`);
    lines.push(``);
  });

  return lines.join('\n');
}
